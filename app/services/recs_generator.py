from __future__ import annotations
from typing import List, Dict

# Небольшая формула приоритета: высокий impact и низкий effort => выше score.
def _priority_score(impact: int, effort: int) -> float:
    # Базовый 100, +12 за каждую ступень impact выше 3, -6 за каждую ступень effort выше 3
    return round(100 + (impact - 3) * 12 - (effort - 3) * 6, 1)

